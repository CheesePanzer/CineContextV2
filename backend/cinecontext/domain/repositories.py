from collections.abc import Sequence
from typing import Any, Protocol
from uuid import UUID

from .entities import CurationRun, EvidenceSnapshot, Film, Passage, RatingSnapshot, Source


class RunRepository(Protocol):
    async def list_recent(self, limit: int = 20) -> Sequence[CurationRun]: ...
    async def get(self, run_id: UUID) -> CurationRun | None: ...
    async def get_for_update(self, run_id: UUID) -> CurationRun | None: ...
    async def create_once(self, run: CurationRun) -> UUID | None: ...
    async def find_by_submission_key(self, submission_key: UUID) -> CurationRun | None: ...
    async def interrupt_active(self, message: str) -> None: ...
    async def delete_with_data(self, run_id: UUID) -> None: ...


class FilmRepository(Protocol):
    async def get(self, film_id: UUID) -> Film | None: ...
    async def find_candidates(self, theme: str, limit: int = 10) -> Sequence[UUID]: ...
    async def get_projection(self, film_id: UUID) -> dict[str, Any] | None: ...
    async def get_posters(self, film_ids: Sequence[UUID]) -> dict[str, str]: ...
    async def save_poster(self, film_id: UUID, poster_path: str) -> None: ...
    async def get_ratings(self, film_id: UUID) -> Sequence[RatingSnapshot]: ...
    async def save_tmdb_film(
        self,
        tmdb_id: int,
        imdb_id: str | None,
        title: str,
        original_title: str,
        facts: dict[str, Any],
        release: str,
        source_url: str,
        kind: str = "tmdb_release",
    ) -> UUID: ...
    async def save_ratings(self, film_id: UUID, ratings: Sequence[dict[str, Any]]) -> None: ...


class ResearchRepository(Protocol):
    async def search_passages(
        self, query: str, film_id: UUID | None, limit: int = 5
    ) -> Sequence[tuple[Passage, Source]]: ...
    def add_tool_call(
        self, run_id: UUID, operation: str, status: str, elapsed_ms: int, detail: dict[str, Any]
    ) -> None: ...
    def add_evidence(self, snapshots: Sequence[EvidenceSnapshot]) -> None: ...
    def save_study(
        self, run: CurationRun, films: Sequence[dict[str, Any]], decisions: dict[str, dict[str, Any]], study: dict[str, Any]
    ) -> None: ...
    async def save_timeline(
        self,
        run: CurationRun,
        study: dict[str, Any],
        views: dict[str, list[dict[str, Any]]],
        valid_edges: Sequence[Any],
        evidence: Sequence[dict[str, Any]],
    ) -> None: ...
